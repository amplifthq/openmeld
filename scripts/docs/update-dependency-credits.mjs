import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const output = new URL("../../docs/dependencies.md", import.meta.url);
const files = execFileSync(
  "git",
  ["ls-files", "-z", "--", "package.json", ":(glob)**/package.json"],
  { cwd: root, encoding: "utf8" }
)
  .split("\0")
  .filter(Boolean)
  .sort();
const manifests = files.map((file) => ({
  file,
  data: JSON.parse(
    readFileSync(new URL(file, new URL("../../", import.meta.url)), "utf8")
  ),
}));
const localNames = new Set(manifests.map(({ data }) => data.name));
const sections = {
  dependencies: "Runtime",
  devDependencies: "Development",
  optionalDependencies: "Optional",
  peerDependencies: "Peer",
};
const dependencies = new Map();
for (const { file, data } of manifests) {
  for (const [section, label] of Object.entries(sections)) {
    for (const [name, spec] of Object.entries(data[section] ?? {})) {
      if (spec.startsWith("workspace:") || localNames.has(name)) {
        continue;
      }
      const entry = dependencies.get(name) ?? {
        specs: new Set(),
        uses: new Set(),
        files: new Set(),
      };
      entry.specs.add(spec);
      entry.uses.add(label);
      entry.files.add(file);
      dependencies.set(name, entry);
    }
  }
}

const escapeCell = (value) =>
  value.replaceAll("|", "&#124;").replaceAll("\n", " ");
const lines = [
  "# Direct dependency index",
  "",
  "<!-- Generated by scripts/docs/update-dependency-credits.mjs. Do not edit by hand. -->",
  "",
  `This index covers **${dependencies.size} external dependency names** declared in`,
  `**${manifests.length} tracked package manifests**, including the repository root.`,
  "Internal workspace packages are excluded. Runtime, development, optional, and",
  "peer are declaration types; they do not establish what ships in a release.",
  "",
  "Versions below are declared requirements, not resolved installation versions.",
  "Catalog references are defined in [pnpm-workspace.yaml](../pnpm-workspace.yaml);",
  "npm aliases retain their declared names and target specifications.",
  "[pnpm-lock.yaml](../pnpm-lock.yaml) records resolved and transitive dependencies.",
  "",
  "For project acknowledgments and system tools, see [Credits](../CREDITS.md).",
  "For copied code and assets, see [Third-party notices](../THIRD_PARTY_NOTICES.md).",
  "This list is not a license audit, a release bill of materials, or a list of",
  "hosted services included with OpenMeld. Check each distributed package's notices.",
  "",
  "Regenerate from the repository root:",
  "",
  "```sh",
  "node scripts/docs/update-dependency-credits.mjs",
  "node scripts/docs/update-dependency-credits.mjs --check",
  "```",
  "",
  "The generator reads tracked package manifests from the working tree. It does",
  "not install packages or query the network. Stage new manifests before running it.",
  "",
  "| Dependency | Declared requirements | Declaration types | Declared in |",
  "| --- | --- | --- | --- |",
];

for (const name of [...dependencies.keys()].sort()) {
  const entry = dependencies.get(name);
  const specs = [...entry.specs]
    .sort()
    .map((s) => `<code>${escapeCell(s)}</code>`)
    .join("<br>");
  const owners = [...entry.files]
    .sort()
    .map((file) => `[${file.replace("/package.json", "")}](../${file})`)
    .join("<br>");
  lines.push(
    `| [${name}](https://www.npmjs.com/package/${name}) | ${specs} | ${[...entry.uses].sort().join(", ")} | ${owners} |`
  );
}

const content = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== content) {
    console.error(
      "Dependency credits are stale. Run node scripts/docs/update-dependency-credits.mjs"
    );
    process.exitCode = 1;
  } else {
    console.log(
      `Dependency credits match ${manifests.length} manifests and ${dependencies.size} external names.`
    );
  }
} else {
  writeFileSync(output, content);
  console.log(
    `Updated docs/dependencies.md with ${dependencies.size} external dependency names.`
  );
}
