#!/usr/bin/env node

import { createRequire } from "node:module";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_DIRECTORY = path.dirname(fileURLToPath(import.meta.url));
const REPOSITORY_ROOT = path.resolve(SCRIPT_DIRECTORY, "..", "..");
const requireFromPinnedWorkspace = createRequire(
  path.join(REPOSITORY_ROOT, "services/auth/package.json")
);
const { build } = requireFromPinnedWorkspace("esbuild");
const DEFAULT_OUTPUT = path.join(
  SCRIPT_DIRECTORY,
  "final-candidate-publisher.bundle.mjs"
);
const GENERATED_BANNER =
  "// Generated by scripts/ci/final-candidate-publisher-build.mjs. Do not edit.";

export async function buildFinalCandidatePublisherBundle(input = {}) {
  const outputPath = path.resolve(input.outputPath ?? DEFAULT_OUTPUT);
  const result = await build({
    absWorkingDir: REPOSITORY_ROOT,
    banner: { js: GENERATED_BANNER },
    bundle: true,
    charset: "utf8",
    entryPoints: ["scripts/ci/final-candidate-publisher.mjs"],
    format: "esm",
    legalComments: "none",
    logLevel: "silent",
    metafile: true,
    minify: false,
    outfile: outputPath,
    packages: "bundle",
    platform: "node",
    sourcemap: false,
    supported: { "template-literal": false },
    target: "node24",
  });
  const unsafeRuntimeImports = Object.values(result.metafile.outputs)
    .flatMap((output) => output.imports)
    .filter((runtimeImport) => runtimeImport.external)
    .map((runtimeImport) => runtimeImport.path)
    .filter((runtimeImport) => !runtimeImport.startsWith("node:"));
  if (unsafeRuntimeImports.length > 0) {
    throw new Error(
      `Final Candidate publisher bundle kept runtime dependencies: ${unsafeRuntimeImports.join(", ")}`
    );
  }
  return outputPath;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    await buildFinalCandidatePublisherBundle({
      outputPath: process.argv[2],
    });
  } catch (error) {
    process.stderr.write(
      `${error instanceof Error ? error.message : String(error)}\n`
    );
    process.exitCode = 1;
  }
}
