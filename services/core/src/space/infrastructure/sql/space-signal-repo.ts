export const listSignalEntriesAfterAnchor = (
  sql: SqlStorage,
  input: {
    afterSignalId: string;
    limit: number;
    filters?: SpaceSignalEntryFilters;
  }
): SignalEntriesAfterAnchorPage | null => {
  const normalizedSignalId = String(input.afterSignalId ?? "").trim();
  if (normalizedSignalId.length === 0) {
    return null;
  }

  const anchorRows = sql
    .exec<SqlSignalAnchorRow>(
      `
        SELECT rowid AS storage_order, ts
        FROM space_signals
        WHERE id = ?
        LIMIT 1
      `,
      normalizedSignalId
    )
    .toArray();
  const anchor = anchorRows[0];
  if (!anchor) {
    return null;
  }

  const where = buildSignalFilterWhereClause(input.filters, "AND");
  const rows = sql
    .exec<SqlSignalRow>(
      `
        SELECT id, ts, payload_json
        FROM space_signals
        WHERE rowid > ?
        ${where.sql}
        ORDER BY rowid ASC
        LIMIT ?
      `,
      anchor.storage_order,
      ...where.params,
      input.limit
    )
    .toArray();

  return {
    entries: rows.map((row) => [
      toSignalStorageKey(row.ts, row.id),
      row.payload_json,
    ]),
    lastSignalId: rows.at(-1)?.id ?? null,
  };
};

export const countPublicTextSignalsAfterDispatchAnchor = (
  sql: SqlStorage,
  input: {
    dispatchId: string;
    afterSignalId: string;
    afterTimestampMs: number;
    excludeProfileId: string;
  }
): number => {
  const normalizedSignalId = String(input.afterSignalId ?? "").trim();
  const normalizedExcludedProfileId = String(
    input.excludeProfileId ?? ""
  ).trim();
  const normalizedAfterTimestampMs = Number(input.afterTimestampMs);
  if (
    normalizedSignalId.length === 0 ||
    normalizedExcludedProfileId.length === 0 ||
    !Number.isSafeInteger(normalizedAfterTimestampMs) ||
    normalizedAfterTimestampMs < 0
  ) {
    return 0;
  }

  const rows = sql
    .exec<{ signal_count?: number }>(
      `
        WITH dispatch_anchor AS (
          SELECT rowid AS anchor_rowid
          FROM space_signals
          WHERE id = ?
          LIMIT 1
        ),
        resolved_anchor AS (
          SELECT (
            SELECT anchor_rowid
            FROM dispatch_anchor
          ) AS anchor_rowid
        )
        SELECT COUNT(*) AS signal_count
        FROM space_signals
        CROSS JOIN resolved_anchor
        WHERE (
          (
            resolved_anchor.anchor_rowid IS NOT NULL
            AND space_signals.rowid > resolved_anchor.anchor_rowid
          )
          OR (
            resolved_anchor.anchor_rowid IS NULL
            AND space_signals.ts > ?
          )
        )
          AND type = 'signal.text'
          AND profile_kind != 'system'
          AND profile_id != ?
          AND COALESCE(json_extract(payload_json, '$.data.meta.transient'), 0) != 1
          AND NOT EXISTS (
            SELECT 1 FROM space_execution_input_outbox AS execution_input
            WHERE execution_input.input_id = json_extract(space_signals.payload_json, '$.data.meta.clientMessageId')
              AND execution_input.queue_state = 'consumed'
              AND execution_input.queue_claim = 'steer'
              AND json_extract(execution_input.signal_json, '$.id') = space_signals.id
              AND json_extract(execution_input.signal_json, '$.data.meta.centerAgentExecutionInput.dispatchId') = ?
              AND json_extract(execution_input.signal_json, '$.data.meta.centerAgentExecutionInput.targetProfileId') = ?
          )
      `,
      normalizedSignalId,
      normalizedAfterTimestampMs,
      normalizedExcludedProfileId,
      input.dispatchId,
      normalizedExcludedProfileId
    )
    .toArray();
  const count = Number(rows[0]?.signal_count ?? 0);
  return Number.isSafeInteger(count) && count > 0 ? count : 0;
};

export type AgentReplyObservationState =
  | "anchor_missing"
  | "changed"
  | "current";

export type AgentReplyObservationTransactionResult<T> =
  | { status: "anchor_missing" | "changed" }
  | { status: "committed"; value: T };

export const readAgentReplyObservationState = (
  sql: SqlStorage,
  input: {
    observedThroughSignalId: string;
    sourceSignalId: string;
    threadId: string | null;
  }
): AgentReplyObservationState => {
  const observedThroughSignalId = String(
    input.observedThroughSignalId ?? ""
  ).trim();
  if (!observedThroughSignalId) {
    return "anchor_missing";
  }
  const sourceSignalId = String(input.sourceSignalId ?? "").trim();
  if (!sourceSignalId) {
    return "anchor_missing";
  }
  const threadId = String(input.threadId ?? "").trim() || null;
  const row = sql
    .exec<{ anchor_exists?: number; context_changed?: number }>(
      `
        WITH observed AS (
          SELECT observed_signal.rowid AS observed_rowid
          FROM space_signals AS observed_signal
          LEFT JOIN space_thread_signal_placements AS observed_placement
            ON observed_placement.signal_id = observed_signal.id
          WHERE observed_signal.id = ?
            AND (
              (
                ? IS NULL
                AND (
                  observed_placement.signal_id IS NULL
                  OR observed_placement.placement = 'root'
                )
              )
              OR (
                ? IS NOT NULL
                AND observed_placement.thread_id = ?
                AND observed_placement.placement IN ('root', 'thread')
              )
            )
          LIMIT 1
        )
        SELECT
          EXISTS(SELECT 1 FROM observed) AS anchor_exists,
          EXISTS(
            SELECT 1
            FROM space_signals AS candidate
            LEFT JOIN space_thread_signal_placements AS placement
              ON placement.signal_id = candidate.id
            CROSS JOIN observed
            WHERE candidate.rowid > observed.observed_rowid
              AND candidate.type IN ('signal.text', 'signal.status')
              AND (candidate.profile_kind != 'system' OR json_extract(candidate.payload_json, '$.data.meta.purpose') = 'space_message_changed')
              AND COALESCE(
                json_extract(candidate.payload_json, '$.data.meta.transient'),
                0
              ) != 1
              AND COALESCE(
                json_extract(candidate.payload_json, '$.data.meta.purpose'),
                ''
              ) NOT IN (?, ?)
              AND (
                (
                  ? IS NULL
                  AND (
                    placement.signal_id IS NULL
                    OR placement.placement = 'root'
                  )
                )
                OR (
                  ? IS NOT NULL
                  AND placement.thread_id = ?
                  AND placement.placement = 'thread'
                )
              )
            LIMIT 1
          ) AS context_changed
      `,
      observedThroughSignalId,
      threadId,
      threadId,
      threadId,
      SPACE_MEMBER_JOIN_NOTICE_PURPOSE,
      SPACE_MEMBER_REMOVE_NOTICE_PURPOSE,
      threadId,
      threadId,
      threadId
    )
    .toArray()[0];
  if (Number(row?.anchor_exists ?? 0) !== 1) {
    return "anchor_missing";
  }
  return Number(row?.context_changed ?? 0) === 1 ? "changed" : "current";
};

export const runAgentReplyObservationGuardedTransaction = <T>(input: {
  observation: {
    observedThroughSignalId: string;
    sourceSignalId: string;
    threadId: string | null;
  } | null;
  operation: () => T;
  storage: {
    sql: SqlStorage;
    transactionSync: (
      closure: () => AgentReplyObservationTransactionResult<T>
    ) => AgentReplyObservationTransactionResult<T>;
  };
}): AgentReplyObservationTransactionResult<T> => {
  if (typeof input.storage.transactionSync !== "function") {
    throw new Error("agent reply publication requires transactionSync");
  }
  const operation = (): AgentReplyObservationTransactionResult<T> => {
    if (input.observation) {
      const state = readAgentReplyObservationState(
        input.storage.sql,
        input.observation
      );
      if (state !== "current") {
        return { status: state };
      }
    }
    return { status: "committed", value: input.operation() };
  };
  return input.storage.transactionSync(operation);
};

export const listSignalEntriesAroundAnchor = (
  sql: SqlStorage,
  input: {
    aroundSignalId: string;
    beforeCount: number;
    afterCount: number;
    filters?: SpaceSignalEntryFilters;
  }
): {
  beforeEntries: SignalEntry[];
  anchorEntry: SignalEntry;
  afterEntries: SignalEntry[];
} | null => {
  const normalizedSignalId = String(input.aroundSignalId ?? "").trim();
  if (normalizedSignalId.length === 0) {
    return null;
  }

  const anchorRows = sql
    .exec<SqlSignalAnchorEntryRow>(
      `
        SELECT rowid AS storage_order, id, ts, payload_json
        FROM space_signals
        WHERE id = ?
        LIMIT 1
      `,
      normalizedSignalId
    )
    .toArray();
  const anchor = anchorRows[0];
  if (!anchor) {
    return null;
  }

  const where = buildSignalFilterWhereClause(input.filters, "AND");
  const beforeRows =
    input.beforeCount > 0
      ? sql
          .exec<SqlSignalRow>(
            `
              SELECT id, ts, payload_json
              FROM space_signals
              WHERE rowid < ?
              ${where.sql}
              ORDER BY rowid DESC
              LIMIT ?
            `,
            anchor.storage_order,
            ...where.params,
            input.beforeCount
          )
          .toArray()
      : [];
  const afterRows =
    input.afterCount > 0
      ? sql
          .exec<SqlSignalRow>(
            `
              SELECT id, ts, payload_json
              FROM space_signals
              WHERE rowid > ?
              ${where.sql}
              ORDER BY rowid ASC
              LIMIT ?
            `,
            anchor.storage_order,
            ...where.params,
            input.afterCount
          )
          .toArray()
      : [];

  return {
    beforeEntries: beforeRows
      .reverse()
      .map((row) => [toSignalStorageKey(row.ts, row.id), row.payload_json]),
    anchorEntry: [
      toSignalStorageKey(anchor.ts, anchor.id),
      anchor.payload_json,
    ],
    afterEntries: afterRows.map((row) => [
      toSignalStorageKey(row.ts, row.id),
      row.payload_json,
    ]),
  };
};

export const deleteOldestSignalRows = (
  sql: SqlStorage,
  limit: number
): number => {
  // Preserve the source's history boundary so first-contact projection cannot
  // mistake a pruned long-lived conversation for a newly initiated one.
  sql.exec(
    `UPDATE space_meta SET archive_cursor_ts = max(coalesce(archive_cursor_ts, 0), coalesce((
    SELECT max(ts) FROM (SELECT ts FROM space_signals ORDER BY ts ASC, id ASC LIMIT ?)
  ), 0))`,
    limit
  );
  sql.exec(
    `DELETE FROM space_recalled_message_drafts WHERE signal_id IN (
    SELECT id FROM space_signals ORDER BY ts ASC, id ASC LIMIT ?
  )`,
    limit
  );
  const result = sql.exec(
    `
      DELETE FROM space_signals
      WHERE id IN (
        SELECT id
        FROM space_signals
        ORDER BY ts ASC, id ASC
        LIMIT ?
      )
    `,
    limit
  );

  // Inbox projection rows share the retained signal's lifetime. Keep pending
  // and failed rows for recovery, but completed rows no longer need to remain
  // once their source signal has aged out of the Space timeline.
  sql.exec(`
    DELETE FROM space_inbox_projection_outbox
    WHERE status = 'completed'
      AND NOT EXISTS (
        SELECT 1
        FROM space_signals
        WHERE space_signals.id = space_inbox_projection_outbox.signal_id
      )
  `);
  sql.exec(`DELETE FROM space_inbox_projection_selections
    WHERE NOT EXISTS (SELECT 1 FROM space_inbox_projection_outbox AS outbox
      WHERE outbox.projection_id = space_inbox_projection_selections.projection_id)`);

  return result.rowsWritten;
};

