function claimFinalReplyPersistence(
  sql: SqlStorage,
  signal: SignalEnvelope
): "duplicate_blocked" | "not_applicable" | "claimed" {
  const claim = resolveFinalReplyClaim(signal);
  if (!claim) {
    return "not_applicable";
  }
  const result = sql.exec(
    `
      INSERT OR IGNORE INTO space_final_reply_claims (
        dispatch_id,
        profile_id,
        signal_id,
        created_at
      )
      VALUES (?, ?, ?, ?)
    `,
    claim.dispatchId,
    claim.profileId,
    signal.id,
    signal.ts
  );
  return result.rowsWritten > 0 ? "claimed" : "duplicate_blocked";
}

function buildSignalFilterWhereClause(
  filters: SpaceSignalEntryFilters | undefined,
  prefix = "WHERE"
): {
  sql: string;
  params: (string | number)[];
} {
  const clauses: string[] = [];
  const params: (string | number)[] = [];
  if (filters?.afterPosition !== undefined) {
    clauses.push("rowid > ?");
    params.push(filters.afterPosition);
  }
  const signalTypes = normalizeUniqueFilterValues(filters?.signalTypes ?? []);
  const profileIds = normalizeUniqueFilterValues(filters?.profileIds ?? []);

  if (filters?.mainTimelineOnly) {
    clauses.push(
      "id NOT IN (SELECT signal_id FROM space_thread_signal_placements WHERE placement = 'thread')"
    );
  }
  if (signalTypes.length > 0) {
    clauses.push(`type IN (${signalTypes.map(() => "?").join(", ")})`);
    params.push(...signalTypes);
    // Mutation cursors belong to incremental reads, never consume a visible
    // history page slot just because the durable event uses signal.text.
    if (!filters?.includeMutationCursors) {
      clauses.push(
        "NOT (profile_kind = 'system' AND COALESCE(json_extract(payload_json, '$.data.meta.purpose'), '') = 'space_message_changed')"
      );
    }
  }
  if (profileIds.length > 0) {
    clauses.push(`profile_id IN (${profileIds.map(() => "?").join(", ")})`);
    params.push(...profileIds);
  }

  if (clauses.length === 0) {
    return {
      sql: "",
      params,
    };
  }

  return {
    sql: `${prefix} ${clauses.join(" AND ")}`,
    params,
  };
}

function normalizeUniqueFilterValues(values: readonly string[]): string[] {
  const normalizedValues = new Set<string>();
  for (const value of values) {
    const normalized = normalizeOptionalString(value);
    if (normalized) {
      normalizedValues.add(normalized);
    }
  }
  return [...normalizedValues];
}

function resolveFinalReplyClaim(
  signal: SignalEnvelope
): { dispatchId: string; profileId: string } | null {
  if (signal.type === "signal.status") {
    const generatedBy = normalizeOptionalString(signal.data.generatedBy);
    if (generatedBy !== "openmeld") {
      return null;
    }
    const dispatchId = normalizeOptionalString(signal.data.dispatchId);
    const profileId = normalizeOptionalString(signal.data.actorProfileId);
    if (!(dispatchId && profileId)) {
      return null;
    }
    return {
      dispatchId,
      profileId,
    };
  }
  if (signal.type === "signal.system_notice") {
    const noticeType = normalizeOptionalString(signal.data.noticeType);
    const generatedBy = normalizeOptionalString(signal.data.generatedBy);
    if (!(generatedBy === "openmeld" && isFinalSystemNoticeType(noticeType))) {
      return null;
    }
    const dispatchId = normalizeOptionalString(signal.data.dispatchId);
    const profileId = normalizeOptionalString(signal.data.actorProfileId);
    if (!(dispatchId && profileId)) {
      return null;
    }
    return {
      dispatchId,
      profileId,
    };
  }
  if (signal.type !== "signal.text") {
    return null;
  }
  const meta = resolveSignalTextMeta(signal);
  const purpose = normalizeOptionalString(meta?.purpose);
  if (!isFinalOutcomeTextPurpose(purpose)) {
    return null;
  }
  const dispatchId = normalizeOptionalString(meta?.dispatchId);
  const profileId = normalizeOptionalString(meta?.targetProfileId);
  const authorProfileId = normalizeOptionalString(signal.profile?.profileId);
  if (!(dispatchId && profileId && authorProfileId === profileId)) {
    return null;
  }
  return {
    dispatchId,
    profileId,
  };
}

function isFinalSystemNoticeType(value: string | null): boolean {
  return (
    value === "terminal_failure" ||
    value === "policy_blocked" ||
    value === "stay_silent" ||
    value === "wake_stopped"
  );
}

function normalizeOptionalString(value: unknown): string | null {
  if (typeof value !== "string") {
    return null;
  }
  const normalized = value.trim();
  return normalized.length > 0 ? normalized : null;
}

function resolveSignalTextMeta(
  signal: SignalEnvelope
): Record<string, unknown> | null {
  if (signal.type !== "signal.text") {
    return null;
  }
  const meta = signal.data?.meta;
  if (!(meta && typeof meta === "object")) {
    return null;
  }
  return meta as Record<string, unknown>;
}

function readSignalRowsFromCursor(
  sql: SqlStorage,
  cursor: string,
  readLimit: number,
  filters?: SpaceSignalEntryFilters
): SqlSignalRow[] {
  const parsedCursor = parseSignalStorageKey(cursor);
  if (!parsedCursor) {
    return [];
  }

  const where = buildSignalFilterWhereClause(filters, "AND");
  return sql
    .exec<SqlSignalRow>(
      `
        SELECT id, ts, payload_json
        FROM space_signals
        WHERE (ts > ? OR (ts = ? AND id >= ?))
        ${where.sql}
        ORDER BY ts ASC, id ASC
        LIMIT ?
      `,
      parsedCursor.ts,
      parsedCursor.ts,
      parsedCursor.id,
      ...where.params,
      readLimit
    )
    .toArray();
}

function readSignalRowsFromAfterTs(
  sql: SqlStorage,
  afterTs: number | null,
  readLimit: number,
  filters?: SpaceSignalEntryFilters
): SqlSignalRow[] {
  const where = buildSignalFilterWhereClause(filters, "AND");
  if (typeof afterTs === "number") {
    return sql
      .exec<SqlSignalRow>(
        `
          SELECT id, ts, payload_json
          FROM space_signals
          WHERE ts >= ?
          ${where.sql}
          ORDER BY ts ASC, id ASC
          LIMIT ?
        `,
        afterTs + 1,
        ...where.params,
        readLimit
      )
      .toArray();
  }

  const initialWhere = buildSignalFilterWhereClause(filters);
  return sql
    .exec<SqlSignalRow>(
      `
        SELECT id, ts, payload_json
        FROM space_signals
        ${initialWhere.sql}
        ORDER BY ts ASC, id ASC
        LIMIT ?
      `,
      ...initialWhere.params,
      readLimit
    )
    .toArray();
}

function clampTimestampMs(value: number): number {
  if (value > MAX_DATE_TIMESTAMP_MS) {
    return MAX_DATE_TIMESTAMP_MS;
  }
  if (value < -MAX_DATE_TIMESTAMP_MS) {
    return -MAX_DATE_TIMESTAMP_MS;
  }
  return value;
}

function toSignalStorageKey(ts: number, signalId: string): string {
  return `${new Date(clampTimestampMs(ts)).toISOString()}${SIGNAL_STORAGE_KEY_DELIMITER}${signalId}`;
}

function parseSignalStorageKey(key: string): { ts: number; id: string } | null {
  const delimiterIndex = key.indexOf(SIGNAL_STORAGE_KEY_DELIMITER);
  if (delimiterIndex <= 0 || delimiterIndex >= key.length - 1) {
    return null;
  }
  if (key.lastIndexOf(SIGNAL_STORAGE_KEY_DELIMITER) !== delimiterIndex) {
    return null;
  }

  const iso = key.slice(0, delimiterIndex);
  const id = key.slice(delimiterIndex + 1);
  if (!(iso.includes("T") && iso.endsWith("Z")) || id.length === 0) {
    return null;
  }

  const parsedTs = Date.parse(iso);
  if (!Number.isFinite(parsedTs)) {
    return null;
  }

  return {
    ts: clampTimestampMs(parsedTs),
    id,
  };
}
