const resolveSignalClientMessageId = (
  signal: SignalEnvelope
): string | null => {
  if (signal.type !== "signal.text") {
    return null;
  }
  return parseOptionalClientMessageId(signal.data.meta?.clientMessageId);
};

export type LatestFormalSignalCandidateCursor = {
  id: string;
  ts: number;
};

export type LatestFormalSignalCandidateEntriesPage = {
  entries: SignalEntry[];
  nextCursor: LatestFormalSignalCandidateCursor | null;
};

export const listLatestFormalSignalCandidateEntriesPage = (
  sql: SqlStorage,
  input: {
    before?: LatestFormalSignalCandidateCursor;
    limit: number;
  }
): LatestFormalSignalCandidateEntriesPage => {
  if (!(Number.isInteger(input.limit) && input.limit > 0)) {
    throw new Error(
      "latest formal signal candidate page limit must be positive"
    );
  }
  const beforeClause = input.before
    ? "AND (ts < ? OR (ts = ? AND id < ?))"
    : "";
  const params = input.before
    ? [input.before.ts, input.before.ts, input.before.id, input.limit]
    : [input.limit];
  const rows = sql
    .exec<SqlSignalRow>(
      `
        SELECT id, ts, payload_json
        FROM space_signals
        WHERE type IN ('signal.text', 'signal.status', 'signal.system_notice')
        ${beforeClause}
        ORDER BY ts DESC, id DESC
        LIMIT ?
      `,
      ...params
    )
    .toArray();
  const lastRow = rows.at(-1);
  return {
    entries: rows.map((row) => [
      toSignalStorageKey(row.ts, row.id),
      row.payload_json,
    ]),
    nextCursor:
      rows.length === input.limit && lastRow
        ? { id: lastRow.id, ts: lastRow.ts }
        : null,
  };
};

