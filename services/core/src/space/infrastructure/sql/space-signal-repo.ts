export const rejectTextSignalClientMessageIfAbsent = (
  sql: SqlStorage,
  input: {
    clientMessageId: string;
    nowMs: number;
    reasonCode: string;
  }
): void => {
  const clientMessageId = parseOptionalClientMessageId(input.clientMessageId);
  if (!clientMessageId) {
    throw new Error("clientMessageId is required");
  }
  const reasonCode = input.reasonCode.trim();
  if (!reasonCode) {
    throw new Error("reasonCode is required");
  }
  if (
    !(
      Number.isInteger(input.nowMs) &&
      input.nowMs >= 0 &&
      input.nowMs <= MAX_DATE_TIMESTAMP_MS
    )
  ) {
    throw new Error("nowMs must be a valid timestamp");
  }
  sql.exec(
    `
      INSERT OR IGNORE INTO space_client_message_rejections (
        client_message_id,
        reason_code,
        rejected_at_ms
      )
      VALUES (?, ?, ?)
    `,
    clientMessageId,
    reasonCode,
    input.nowMs
  );
};

