export const COMMAND_ENTRY_ROUTE_KEYS = Object.freeze(
  Object.keys(COMMAND_ENTRY_NAME_BY_ROUTE).sort((left, right) =>
    left.localeCompare(right)
  )
);

export function resolveCommandEntryNameFromRoute(
  route: string
): CommandEntryName | null {
  return (
    COMMAND_ENTRY_NAME_BY_ROUTE[
      route as keyof typeof COMMAND_ENTRY_NAME_BY_ROUTE
    ] ?? null
  );
}

export function resolveCommandEntryNameFromTokens(
  tokens: string[]
): CommandEntryName | null {
  const normalized = tokens
    .map((token) => token.trim())
    .filter((token) => token.length > 0)
    .join(" ");
  if (normalized.length === 0) {
    return resolveCommandEntryNameFromRoute("");
  }
  return resolveCommandEntryNameFromRoute(normalized);
}
